// 去掉大类后的前几个中文标签；全是大类时退回原顺序
export function specificLabels(labels: { id: string }[], count: number) {
  const specific = labels.filter(label => !genericLabels.has(label.id))
  const picked = (specific.length ? specific : labels).slice(0, count)
  return picked.map(label => visionLabelZh[label.id] ?? label.id)
}
